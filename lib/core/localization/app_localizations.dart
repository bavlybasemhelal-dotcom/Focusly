  /// Translates the given key or returns fallback, replacing placeholder arguments if provided
  String tr(String key, {Map<String, String>? args}) {
    final languageCode = locale.languageCode;
    String text = _localizedValues[languageCode]?[key] ??
        _localizedValues['en']?[key] ??
        key;
    if (args != null) {
      args.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }

  /// Formats date according to active locale
  String formatLocalizedDate(DateTime date) {
    if (locale.languageCode == 'ar') {
      final days = [
        'الإثنين',
        'الثلاثاء',
        'الأربعاء',
        'الخميس',
        'الجمعة',
        'السبت',
        'الأحد'
      ];
      final months = [
        'يناير',
        'فبراير',
        'مارس',
        'أبريل',
        'مايو',
        'يونيو',
        'يوليو',
        'أغسطس',
        'سبتمبر',
        'أكتوبر',
        'نوفمبر',
        'ديسمبر'
      ];
      final dayName = days[date.weekday - 1];
      final monthName = months[date.month - 1];

      // Convert number to eastern arabic numerals
      final arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
      final dayStr = date.day.toString().split('').map((char) {
        final digit = int.tryParse(char);
        return digit != null ? arabicDigits[digit] : char;
      }).join('');

      return '$dayName، $dayStr $monthName';
    } else {
      final days = [
        'Monday',
        'Tuesday',
        'Wednesday',
        'Thursday',
        'Friday',
        'Saturday',
        'Sunday'
      ];
      final months = [
        'January',
        'February',
        'March',
        'April',
        'May',
        'June',
        'July',
        'August',
        'September',
        'October',
        'November',
        'December'
      ];
      final dayName = days[date.weekday - 1];
      final monthName = months[date.month - 1];
      return '$dayName, $monthName ${date.day}';
    }
  }
